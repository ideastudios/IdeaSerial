package com.github.ideastudios.serialport;

import android.util.Log;

import java.io.File;
import java.io.FileDescriptor;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;

public class SerialPort {

    private static final String TAG = "SerialPort";

    /*
     * Do not remove or rename the field mFd: it is used by native method close();
     */
    private FileDescriptor mFd;
    private FileInputStream mFileInputStream;
    private FileOutputStream mFileOutputStream;

    /**
     * 完整参数构造：数据位/停止位/校验位/流控
     *
     * @param parity      0=无 1=奇 2=偶 3=标 4=空（与 usb-serial-for-android 常量一致）
     * @param flowcontrol 0=无 1=RTS/CTS 2=XON/XOFF
     */
    public SerialPort(File device, int baudrate, int databits, int stopbits,
                      int parity, int flowcontrol, int flags)
            throws SecurityException, IOException {

        /* Check access permission */
        if (!device.canRead() || !device.canWrite()) {
            try {
                /* Missing read/write permission, trying to chmod the file */
                Process su;
                su = Runtime.getRuntime().exec("/system/bin/su");
                String cmd = "chmod 666 " + device.getAbsolutePath() + "\n"
                        + "exit\n";
                su.getOutputStream().write(cmd.getBytes());
                if ((su.waitFor() != 0) || !device.canRead()
                        || !device.canWrite()) {
                    throw new SecurityException();
                }
            } catch (Exception e) {
                e.printStackTrace();
                throw new SecurityException();
            }
        }

        mFd = open(device.getAbsolutePath(), baudrate, databits, stopbits,
                parity, flowcontrol, flags);
        if (mFd == null) {
            Log.e(TAG, "native open returns null");
            throw new IOException();
        }
        mFileInputStream = new FileInputStream(mFd);
        mFileOutputStream = new FileOutputStream(mFd);
    }

    /** 兼容旧接口：默认 8N1、无流控 */
    public SerialPort(File device, int baudrate, int flags)
            throws SecurityException, IOException {
        this(device, baudrate, 8, 1, 0, 0, flags);
    }

    // Getters and setters
    public InputStream getInputStream() {
        return mFileInputStream;
    }

    public OutputStream getOutputStream() {
        return mFileOutputStream;
    }

    // JNI
    private native static FileDescriptor open(String path, int baudrate, int databits,
                                              int stopbits, int parity, int flowcontrol,
                                              int flags);

    public native void close();

    static {
        System.loadLibrary("serialport");
    }
}
